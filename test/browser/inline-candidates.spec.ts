import { test, expect } from "@playwright/test";
import fs from "node:fs/promises";

const evidence = "harness/build/issue-12-evidence";
for (const viewport of [{ name: "desktop", width: 1440, height: 900 }, { name: "mobile", width: 390, height: 844 }]) {
  test("Issue12 inline candidates, explicit confirmation and automatic collapse " + viewport.name, async ({ page, request }) => {
    await fs.mkdir(evidence, { recursive: true });
    await request.post("/__test/reset");
    await request.post("/__test/control", { data: { candidateCount: 7 } });
    await page.setViewportSize(viewport);
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("/explore");
    const region = page.getByRole("region", { name: "地点解析候选" });
    const input = page.getByLabel("地点", { exact: true });
    await expect(region).toHaveCount(0);
    await input.fill("深圳北站");
    await page.getByRole("button", { name: "解析地点", exact: true }).click();
    await expect(region).toBeVisible();
    await expect(region).toBeFocused();
    await expect(page.getByRole("dialog")).toHaveCount(0);
    await expect(page.locator(".explore-dialog-overlay")).toHaveCount(0);
    await expect(page.locator(".candidate-button")).toHaveCount(5);
    const expanded = await region.boundingBox();
    const map = await page.locator(".workspace-map").boundingBox();
    const top = await page.locator(".workspace-location-row").boundingBox();
    expect(expanded!.y).toBeGreaterThanOrEqual(top!.y + top!.height);
    expect(map!.y).toBeGreaterThanOrEqual(expanded!.y + expanded!.height);
    expect(map!.height).toBeGreaterThan(100);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true);
    await page.screenshot({ path: evidence + "/" + viewport.name + "-expanded.png", fullPage: true, animations: "disabled" });
    await page.getByRole("button", { name: "查看更多地点" }).click();
    await expect(page.locator(".candidate-button")).toHaveCount(7);
    await page.getByRole("button", { name: /深圳北站西广场/ }).focus();
    await page.keyboard.press("Enter");
    await expect(region).toHaveCount(0);
    await expect(input).toHaveCount(0);
    await expect(page.getByRole("dialog")).toHaveCount(0);
    await expect(page.locator(".location-summary")).toContainText("深圳北站西广场");
    await expect(page.getByRole("button", { name: "附近生活服务", exact: true })).toBeFocused();
    const collapsed = await page.locator(".workspace-toolbar").boundingBox();
    expect(collapsed!.height).toBeLessThan(top!.height + expanded!.height);
    await page.screenshot({ path: evidence + "/" + viewport.name + "-confirmed.png", fullPage: true, animations: "disabled" });
    const data = await (await request.get("/__test/evidence")).json();
    expect(data.requests.filter((r: { path: string }) => r.path === "/api/search")).toHaveLength(0);
    await page.getByRole("button", { name: "修改地点" }).click();
    await expect(input).toBeFocused();
    await expect(input).toHaveValue("深圳北站");
    await expect(region).toHaveCount(0);
    await expect(page.locator(".location-summary")).toHaveCount(0);
    await page.getByRole("button", { name: "解析地点", exact: true }).click();
    await expect(region).toBeVisible();
    await page.getByRole("button", { name: /没找到想要的地点？试试补充/ }).click();
    await expect(region).toHaveCount(0);
    await expect(input).toBeFocused();
    await expect(input).toHaveValue("深圳北站");
    await expect(page.locator("#location-refine-help")).toBeVisible();
    expect(await input.evaluate((node) => (node as HTMLInputElement).selectionStart)).toBe(4);
    expect(errors).toEqual([]);
    await fs.writeFile(evidence + "/" + viewport.name + "-geometry.json", JSON.stringify({ viewport, top, expanded, map, collapsed }, null, 2));
  });
}
